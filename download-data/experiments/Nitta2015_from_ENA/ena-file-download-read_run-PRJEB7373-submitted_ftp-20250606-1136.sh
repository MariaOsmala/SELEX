# Divergent morphology of species has largely been ascribed to genetic differences in 
# the tissue-specific expression of proteins, which could be achieved by divergence in 
# cis-regulatory elements or by altering the binding specificity of transcription factors (TFs). 
# The relative importance of the latter has been difficult to assess, as previous systematic analyses 
# of TF binding specificity have been performed using different methods in different species. 
# To address this, we determined the binding specificities of more than 242 Drosophila TFs, 
